-- Additive content collections. No existing posts, branches or reservations are replaced.
create table if not exists public.cms_updates (
  id bigint generated by default as identity primary key,
  title text not null default '', category text not null default 'news' check (category in ('news', 'event', 'announcement')),
  summary text not null default '', cover_image text not null default '',
  body_json jsonb not null default '{"type":"doc","content":[]}',
  is_published boolean not null default false, published_at timestamptz,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now(),
  check (jsonb_typeof(body_json) = 'object' and coalesce(body_json->>'type', '') = 'doc'),
  check (not is_published or (length(trim(title)) > 0 and length(trim(summary)) > 0 and length(trim(cover_image)) > 0 and jsonb_path_exists(body_json, '$.**.text ? (@ != "")')))
);
create index if not exists cms_updates_public_order on public.cms_updates(is_published, published_at desc, id desc);
create table if not exists public.cms_alumni (
  id bigint generated by default as identity primary key,
  name text not null default '', image text not null default '', batch text not null default '',
  company text not null default '', position text not null default '',
  display_order integer not null default 0 check (display_order >= 0),
  is_published boolean not null default false,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now(),
  check (not is_published or (length(trim(name)) > 0 and length(trim(image)) > 0 and length(trim(batch)) > 0 and length(trim(company)) > 0 and length(trim(position)) > 0))
);
create index if not exists cms_alumni_public_order on public.cms_alumni(is_published, display_order, id);

create or replace function public.stamp_publishing_content() returns trigger language plpgsql set search_path = public, pg_temp as $$
begin
  new.updated_at := now();
  if tg_op = 'INSERT' then new.created_at := now(); else new.created_at := old.created_at; end if;
  if tg_table_name = 'cms_updates' then
    if tg_op = 'INSERT' then
      new.published_at := case when new.is_published then now() else null end;
    else
      new.published_at := coalesce(old.published_at, case when new.is_published then now() else null end);
    end if;
  end if;
  return new;
end;
$$;

do $$
declare table_name text; policy_row record;
begin
  foreach table_name in array array['cms_updates', 'cms_alumni'] loop
    execute format('alter table public.%I enable row level security', table_name);
    execute format('revoke all on table public.%I from public, anon, authenticated', table_name);
    execute format('grant select on table public.%I to anon', table_name);
    execute format('grant select, insert, update, delete on table public.%I to authenticated', table_name);
    for policy_row in select policyname from pg_policies where schemaname = 'public' and tablename = table_name loop
      execute format('drop policy %I on public.%I', policy_row.policyname, table_name);
    end loop;
    execute format('create policy "Published content is public" on public.%I for select to anon, authenticated using (is_published)', table_name);
    execute format('create policy "Allowlisted admins manage content" on public.%I for all to authenticated using (public.is_admin()) with check (public.is_admin())', table_name);
    execute format('grant usage, select on sequence %s to authenticated', pg_get_serial_sequence('public.' || table_name, 'id'));
    execute format('drop trigger if exists stamp_publishing_content on public.%I', table_name);
    execute format('create trigger stamp_publishing_content before insert or update on public.%I for each row execute function public.stamp_publishing_content()', table_name);
  end loop;
end;
$$;

-- Older frontends omit branch_key. Keep the existing constraints and valid keys.
create or replace function public.ensure_branch_key() returns trigger language plpgsql set search_path = public, pg_temp as $$
begin
  if new.branch_key is null or length(trim(new.branch_key)) = 0 then
    new.branch_key := 'branch-' || gen_random_uuid()::text;
  end if;
  return new;
end;
$$;
alter table public.cms_branches alter column branch_key set default ('branch-' || gen_random_uuid()::text);
drop trigger if exists ensure_branch_key on public.cms_branches;
create trigger ensure_branch_key before insert on public.cms_branches for each row execute function public.ensure_branch_key();

create or replace function public.cms_alumni_batches() returns table(batch text)
language sql stable security invoker set search_path = public, pg_temp as $$
  select distinct a.batch from public.cms_alumni a where a.is_published and length(trim(a.batch)) > 0 order by a.batch;
$$;
revoke all on function public.cms_alumni_batches() from public;
grant execute on function public.cms_alumni_batches() to anon, authenticated;
notify pgrst, 'reload schema';
